        public static readonly IReadOnlyDictionary<string, Font> Fonts = new Dictionary<string, Font>
        {
            ["mini"] = new Font(5, 2, 1, MINI),
            ["big"] = new Font(7, 3, 1, BIG),
        };

        // JS: F.glyphs[ch] ?? F.glyphs[ch.toUpperCase()]
        Glyph Find(char ch) => Glyphs.TryGetValue(ch, out Glyph g) || Glyphs.TryGetValue(char.ToUpperInvariant(ch), out g) ? g : null;

        /// <summary>Width in font pixels of a string (before scaling).</summary>
        public static int TextWidth(string str, string font = "mini")
        {
            Font F = Fonts[font];
            int w = 0;
            foreach (char ch in str)
            {
                Glyph g = F.Find(ch);
                w += (g != null ? g.W : F.Space) + F.Gap;
            }
            return Math.Max(0, w - F.Gap);
        }

        /// <summary>Calls plot(x, y) for every inked font pixel of str, with the top-left of the text at (0, 0).</summary>
        public static void RasterText(string str, string font, Action<int, int> plot)
        {
            Font F = Fonts[font];
            int x = 0;
            foreach (char ch in str)
            {
                Glyph g = F.Find(ch);
                if (g == null)
                {
                    x += F.Space + F.Gap;
                    continue;
                }
                for (int r = 0; r < F.H; r++)
                    for (int c = 0; c < g.W; c++)
                        if (g.Rows[r][c]) plot(x + c, r);
                x += g.W + F.Gap;
            }
        }
