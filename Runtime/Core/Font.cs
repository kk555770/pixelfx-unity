        public sealed class Glyph
        {
            public readonly int W;
            public readonly bool[][] Rows;

            public Glyph(int w, bool[][] rows)
            {
                W = w;
                Rows = rows;
            }
        }

        public readonly int H, Space, Gap;
        public readonly IReadOnlyDictionary<char, Glyph> Glyphs;

        Font(int h, int space, int gap, Dictionary<char, string> table)
        {
            H = h;
            Space = space;
            Gap = gap;
            var glyphs = new Dictionary<char, Glyph>();
            foreach (var kv in table)
            {
                string[] rows = kv.Value.Split('|');
                if (rows.Length != h) throw new InvalidOperationException($"glyph {kv.Key} has {rows.Length} rows, expected {h}");
                glyphs[kv.Key] = new Glyph(rows[0].Length, Array.ConvertAll(rows, r => Array.ConvertAll(r.ToCharArray(), c => c == '#')));
            }
            Glyphs = glyphs;
        }

