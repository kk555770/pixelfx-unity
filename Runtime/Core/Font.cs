    /// Two pixel fonts: "mini" (3x5) for small numbers and tags, "big" (5x7) for words like LEVEL UP. Glyphs are trimmed to their
    /// inked columns, so text sets proportionally (an I is narrower than an M). A port of pixelfx's src/core/font.js.
