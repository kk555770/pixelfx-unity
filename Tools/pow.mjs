// The JS side of Px.Pow (Runtime/Core/PxPow.cs): Math.pow correctly rounded, so the JS original and the port compute the
// same doubles. This is Px.Pow's double-double path without its quicker first try, which returns the same doubles.
//   import { pow } from "./pow.mjs"; Math.pow = pow;            every Math.pow call
//   register("./pow.mjs", import.meta.url, { data: { esbuild, src } })
//                                                               and every ** in the modules under src, through esbuild
let esbuild, src;

export async function initialize(data) {
  src = data.src;
  esbuild = (await import(data.esbuild)).default;
}

// esbuild lowers a ** b to __pow(a, b), with __pow = Math.pow read when the module runs
export async function load(url, context, nextLoad) {
  const loaded = await nextLoad(url, context);
  if (!url.startsWith(src) || loaded.format !== "module") return loaded;
  const { code } = esbuild.transformSync(String(loaded.source), { loader: "js", format: "esm", supported: { "exponent-operator": false }, sourcefile: url });
  return { ...loaded, source: code };
}

/** Math.pow as V8 computes it for squares, square roots, a NaN exponent and 1 or -1 to an infinite power; otherwise x^y rounded to the nearest double. */
export function pow(x, y) {
  if (Number.isNaN(y)) return NaN;
  if (!Number.isFinite(y) && !Number.isNaN(y) && (x === 1 || x === -1)) return NaN;
  if (y === 2) return x * x;
  if (y === 0.5) return x === -Infinity ? Infinity : Math.sqrt(x + 0);
  if (x < 0 && Number.isFinite(x) && Number.isFinite(y) && y === Math.floor(y)) return y % 2 !== 0 ? -roundedPow(-x, y) : roundedPow(-x, y);
  return roundedPow(x, y);
}

const POW = Math.pow;

function roundedPow(x, y) {
  if (!(x > 0) || !Number.isFinite(x) || !Number.isFinite(y) || y === 0 || x === 1) return POW(x, y);
  const [lh, ll] = ln(x);
  const estimate = y * lh;
  if (estimate > 710) return Infinity;
  if (estimate < -746) return 0; // below half the smallest subnormal
  let [zh, zl] = twoProd(y, lh);
  [zh, zl] = fastTwoSum(zh, zl + y * ll);
  return exp(zh, zl);
}

