// ln x = e ln 2 + ln c + 2 atanh(u), with c the centre of x's 1/128 slice of [1, 2) and u = (m - c) / (m + c), |u| <= 2^-9
function ln(x) {
  view.setFloat64(0, x);
  let e = (view.getUint32(0) >>> 20) - 1023;
  if (e === -1023) {
    view.setFloat64(0, x * 18014398509481984); // 2^54
    e = (view.getUint32(0) >>> 20) - 1023 - 54;
  }
  const i = (view.getUint32(0) >>> 13) & 127;
  view.setUint32(0, (view.getUint32(0) & 0x000fffff) | 0x3ff00000);
  const m = view.getFloat64(0), c = 1 + (i + 0.5) / 128;

  const [dh, dl] = twoSum(m, c);
  const num = m - c, q1 = num / dh;
  const [ph, pl] = twoProd(q1, dh);
  const q2 = (num - ph - pl - q1 * dl) / dh;
  const [uh, ul] = fastTwoSum(q1, q2);

  // 2 atanh(u) = 2u + u t (2/3 + t (2/5 + t (2/7 + t (2/9 + t 2/11)))), t = u^2
  const [th, tl] = mul(uh, ul, uh, ul);
  const s = 0.4 + th * (2 / 7 + th * (2 / 9 + th * (2 / 11)));
  let [ih, il] = fastTwoSum(TWO_THIRDS_HI, th * s);
  il += TWO_THIRDS_LO;
  let [wh, wl] = mul(uh, ul, th, tl);
  [wh, wl] = mul(wh, wl, ih, il);
  let [ah, al] = add(2 * uh, 2 * ul, wh, wl);

  [ah, al] = add(LN_C[2 * i], LN_C[2 * i + 1], ah, al);
  const [eh, el] = twoProd(e, LN2_HI);
  return add(eh, el + e * LN2_LO, ah, al);
}

// e^z = 2^k 2^(j/128) e^r, z = (128k + j) ln2/128 + r, |r| <= ln2/256
function exp(zh, zl) {
  const n = roundEven(zh * INV_LN2_OVER_128), k = n >> 7, j = n & 127;
  const [ph, pl] = twoProd(n, LN2_OVER_128_HI);
  const [rh, rl] = fastTwoSum(zh - ph, zl - pl - n * LN2_OVER_128_LO);

  // e^r - 1 = r + r^2 (1/2 + r (1/6 + r (1/24 + r q))), q = 1/120 + r/720 + ... in double
  const q = 1 / 120 + rh * (1 / 720 + rh * (1 / 5040 + rh * (1 / 40320 + rh * (1 / 362880))));
  let [ch, cl] = fastTwoSum(INV_TWENTY_FOUR_HI, rh * q);
  cl += INV_TWENTY_FOUR_LO;
  [ch, cl] = mul(rh, rl, ch, cl);
  [ch, cl] = add(INV_SIX_HI, INV_SIX_LO, ch, cl);
  [ch, cl] = mul(rh, rl, ch, cl);
  [ch, cl] = add(0.5, 0, ch, cl);
  const [sh, sl] = mul(rh, rl, rh, rl);
  [ch, cl] = mul(sh, sl, ch, cl);
  let [mh, ml] = add(rh, rl, ch, cl);

  const th = EXP2_J[2 * j], tl = EXP2_J[2 * j + 1];
  [mh, ml] = mul(th, tl, mh, ml);
  [mh, ml] = add(th, tl, mh, ml);
  const result = mh + ml;
  if (k > 1023) return result * 2 * powerOfTwo(k - 1);
  if (k > -1022 || (k === -1022 && result >= 1)) return result * powerOfTwo(k);

  // a subnormal: round (mh + ml) 2^(k + 1074) to an integer once, halves to even, then scale it by 2^-1074 exactly
  const scale = powerOfTwo(k + 1074), a = mh * scale;
  let units = roundEven(a);
  const f = (a - units) + ml * scale;
  if (f > 0.5 || (f === 0.5 && units % 2 !== 0)) units++;
  else if (f < -0.5 || (f === -0.5 && units % 2 !== 0)) units--;
  return units * Number.MIN_VALUE;
}

// C#'s Math.Round: halves to even
function roundEven(v) {
  const r = Math.round(v);
  return r - v === 0.5 && r % 2 !== 0 ? r - 1 : r;
}

function powerOfTwo(k) {
  view.setUint32(0, (k + 1023) << 20);
  view.setUint32(4, 0);
  return view.getFloat64(0);
}

// ---- double-double arithmetic: a value is hi + lo with |lo| <= half an ulp of hi

function twoSum(a, b) {
  const s = a + b, bb = s - a;
  return [s, (a - (s - bb)) + (b - bb)];
}

function fastTwoSum(a, b) {
  const s = a + b;
  return [s, b - (s - a)];
}

// Dekker's product, as Px.Pow computes it
function twoProd(a, b) {
  const p = a * b;
  const ta = 134217729 * a, ah = ta - (ta - a), al = a - ah;
  const tb = 134217729 * b, bh = tb - (tb - b), bl = b - bh;
  return [p, ((ah * bh - p) + ah * bl + al * bh) + al * bl];
}

function add(ah, al, bh, bl) {
  let [s, e] = twoSum(ah, bh);
  const [t, f] = twoSum(al, bl);
  [s, e] = fastTwoSum(s, e + t);
  return fastTwoSum(s, e + f);
}

function mul(ah, al, bh, bl) {
  const [p, e] = twoProd(ah, bh);
  return fastTwoSum(p, e + (ah * bl + al * bh));
}

